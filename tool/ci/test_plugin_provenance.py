"""Regression tests for plugin_provenance.py.

The module used to read pubspec.lock with json.loads. The lock is YAML, so every
release build failed with a parse error. These tests pin the lock reader against
the exact shape `dart pub get` writes, and pin the refusal paths: a path
dependency, an unexpected URL, a short ref and a tampered native library.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parent))

import plugin_provenance as provenance  # noqa: E402

COMMIT = "0123456789abcdef0123456789abcdef01234567"
PLUGIN_URL = "https://github.com/azurekiln2333/qflistudio-git"

LOCK_TEMPLATE = """\
# Generated by pub
# See https://dart.dev/tools/pub/glossary#lockfile
packages:
  archive:
    dependency: transitive
    description:
      name: archive
      sha256: "abc123"
      url: "https://pub.dev"
    source: hosted
    version: "4.0.7"
  qfli_git:
    dependency: "direct main"
    description:
      path: "."
      ref: main
      resolved-ref: "{commit}"
      url: "{url}"
    source: {source}
    version: "0.2.0"
sdks:
  dart: ">=3.11.5 <4.0.0"
"""


def lock_text(commit: str = COMMIT, url: str = PLUGIN_URL, source: str = "git") -> str:
    return LOCK_TEMPLATE.format(commit=commit, url=url, source=source)


class LockReaderTests(unittest.TestCase):
    def write_lock(self, directory: Path, text: str) -> Path:
        path = directory / "pubspec.lock"
        path.write_text(text, encoding="utf-8")
        return path

    def test_pubspec_lock_is_not_json(self) -> None:
        """The old json.loads path must not come back."""
        with tempfile.TemporaryDirectory() as work:
            path = self.write_lock(Path(work), lock_text())
            with self.assertRaises(json.JSONDecodeError):
                json.loads(path.read_text(encoding="utf-8"))

    def test_subset_reader_reads_real_lock_shape(self) -> None:
        data = provenance.parse_lock_subset(lock_text())
        self.assertEqual(sorted(data["packages"]), ["archive", "qfli_git"])
        entry = data["packages"]["qfli_git"]
        self.assertEqual(entry["source"], "git")
        self.assertEqual(entry["version"], "0.2.0")
        self.assertEqual(entry["description"]["resolved-ref"], COMMIT)
        self.assertEqual(entry["description"]["url"], PLUGIN_URL)

    def test_subset_reader_keeps_hosted_entries(self) -> None:
        data = provenance.parse_lock_subset(lock_text())
        self.assertEqual(data["packages"]["archive"]["description"]["name"], "archive")
        self.assertEqual(
            data["packages"]["archive"]["description"]["sha256"], "abc123"
        )

    def test_lock_entry_accepts_a_git_pin(self) -> None:
        with tempfile.TemporaryDirectory() as work:
            root = Path(work)
            self.write_lock(root, lock_text())
            entry = provenance.lock_entry(root)
        self.assertEqual(entry["commit"], COMMIT)
        self.assertEqual(entry["version"], "0.2.0")
        self.assertIn("qflistudio-git", entry["url"])

    def test_lock_entry_rejects_a_path_dependency(self) -> None:
        with tempfile.TemporaryDirectory() as work:
            root = Path(work)
            self.write_lock(root, lock_text(source="path"))
            with self.assertRaises(provenance.ProvenanceError) as raised:
                provenance.lock_entry(root)
        self.assertIn("not a Git commit", str(raised.exception))

    def test_lock_entry_rejects_an_unexpected_url(self) -> None:
        with tempfile.TemporaryDirectory() as work:
            root = Path(work)
            self.write_lock(root, lock_text(url="https://github.com/someone/else"))
            with self.assertRaises(provenance.ProvenanceError) as raised:
                provenance.lock_entry(root)
        self.assertIn("unexpected URL", str(raised.exception))

    def test_lock_entry_rejects_a_short_ref(self) -> None:
        with tempfile.TemporaryDirectory() as work:
            root = Path(work)
            self.write_lock(root, lock_text(commit="3e3c489"))
            with self.assertRaises(provenance.ProvenanceError) as raised:
                provenance.lock_entry(root)
        self.assertIn("full Git commit", str(raised.exception))

    def test_lock_entry_rejects_a_non_hex_ref(self) -> None:
        with tempfile.TemporaryDirectory() as work:
            root = Path(work)
            self.write_lock(root, lock_text(commit="z" * 40))
            with self.assertRaises(provenance.ProvenanceError) as raised:
                provenance.lock_entry(root)
        self.assertIn("hexadecimal", str(raised.exception))

    def test_lock_entry_requires_the_plugin_entry(self) -> None:
        with tempfile.TemporaryDirectory() as work:
            root = Path(work)
            self.write_lock(
                root,
                "packages:\n  archive:\n    source: hosted\n    version: \"1.0.0\"\n",
            )
            with self.assertRaises(provenance.ProvenanceError) as raised:
                provenance.lock_entry(root)
        self.assertIn("no qfli_git entry", str(raised.exception))

    def test_missing_lock_fails(self) -> None:
        with tempfile.TemporaryDirectory() as work:
            with self.assertRaises(provenance.ProvenanceError):
                provenance.lock_entry(Path(work))

    def test_empty_packages_section_fails(self) -> None:
        with tempfile.TemporaryDirectory() as work:
            path = self.write_lock(Path(work), "packages:\nsdks:\n  dart: '>=3.11.5'\n")
            with self.assertRaises(provenance.ProvenanceError) as raised:
                provenance.load_lock_yaml(path)
        self.assertIn("no packages section", str(raised.exception))


class NativeStateTests(unittest.TestCase):
    def build_plugin(self, root: Path) -> dict:
        (root / "tool/ci").mkdir(parents=True)
        (root / "native/include").mkdir(parents=True)
        (root / "lib/src").mkdir(parents=True)
        (root / "assets").mkdir(parents=True)
        (root / "android/src/main/jniLibs/arm64-v8a").mkdir(parents=True)

        contract = {
            "apiVersion": 2,
            "requiredExports": ["qg_api_version", "qg_add_all"],
        }
        contract_path = root / "tool/ci/native_contract.json"
        contract_path.write_text(json.dumps(contract), encoding="utf-8")
        (root / "lib/src/bindings.dart").write_text(
            "const int qgApiVersion = 2;\n", encoding="utf-8"
        )
        (root / "native/include/qfli_git.h").write_text(
            "#define QG_API_VERSION 2\n", encoding="utf-8"
        )
        (root / "assets/cacert.pem").write_text("CA BUNDLE\n", encoding="utf-8")
        library = root / "android/src/main/jniLibs/arm64-v8a/libqfli_git.so"
        library.write_bytes(b"\x7fELF payload")

        lock = {
            "schemaVersion": 2,
            "apiVersion": 2,
            "requiredExports": contract["requiredExports"],
            "contractSha256": hashlib.sha256(contract_path.read_bytes()).hexdigest(),
            "source": {
                "repository": PLUGIN_URL,
                "release": "native-v0.2.0",
                "run": "https://github.com/azurekiln2333/qflistudio-git/actions/runs/1",
                "commit": COMMIT,
                "commits": {"android": COMMIT, "ios": COMMIT, "ohos": COMMIT},
            },
            "files": [
                {
                    "path": "android/src/main/jniLibs/arm64-v8a/libqfli_git.so",
                    "abi": "arm64-v8a",
                    "bytes": library.stat().st_size,
                    "sha256": hashlib.sha256(library.read_bytes()).hexdigest(),
                }
            ],
        }
        (root / "native_libs.lock.json").write_text(
            json.dumps(lock), encoding="utf-8"
        )
        return {"contract": contract, "lock": lock, "library": library}

    def test_consistent_plugin_state_passes(self) -> None:
        with tempfile.TemporaryDirectory() as work:
            root = Path(work)
            state = self.build_plugin(root)
            contract = provenance.plugin_contract(root)
            native = provenance.plugin_native_state(root, contract)
        self.assertEqual(native["apiVersion"], 2)
        self.assertEqual(native["commit"], COMMIT)
        self.assertEqual(native["release"], "native-v0.2.0")
        self.assertEqual(len(native["cacert"]), 64)
        self.assertEqual(state["lock"]["apiVersion"], 2)

    def test_tampered_library_fails(self) -> None:
        with tempfile.TemporaryDirectory() as work:
            root = Path(work)
            state = self.build_plugin(root)
            state["library"].write_bytes(b"\x7fELF tampered")
            contract = provenance.plugin_contract(root)
            with self.assertRaises(provenance.ProvenanceError) as raised:
                provenance.plugin_native_state(root, contract)
        self.assertIn("different", str(raised.exception))

    def test_legacy_schema_one_lock_fails(self) -> None:
        with tempfile.TemporaryDirectory() as work:
            root = Path(work)
            state = self.build_plugin(root)
            lock = dict(state["lock"])
            lock["schemaVersion"] = 1
            (root / "native_libs.lock.json").write_text(json.dumps(lock), encoding="utf-8")
            contract = provenance.plugin_contract(root)
            with self.assertRaises(provenance.ProvenanceError) as raised:
                provenance.plugin_native_state(root, contract)
        self.assertIn("schema 2", str(raised.exception))

    def test_divergent_platform_commit_fails(self) -> None:
        with tempfile.TemporaryDirectory() as work:
            root = Path(work)
            state = self.build_plugin(root)
            lock = state["lock"]
            lock["source"]["commits"]["ios"] = "f" * 40
            (root / "native_libs.lock.json").write_text(json.dumps(lock), encoding="utf-8")
            contract = provenance.plugin_contract(root)
            with self.assertRaises(provenance.ProvenanceError):
                provenance.plugin_native_state(root, contract)

    def test_missing_contract_fails(self) -> None:
        with tempfile.TemporaryDirectory() as work:
            root = Path(work)
            self.build_plugin(root)
            (root / "tool/ci/native_contract.json").unlink()
            with self.assertRaises(provenance.ProvenanceError) as raised:
                provenance.plugin_contract(root)
        self.assertIn("native_contract.json", str(raised.exception))

    def test_binding_api_mismatch_fails(self) -> None:
        with tempfile.TemporaryDirectory() as work:
            root = Path(work)
            self.build_plugin(root)
            (root / "lib/src/bindings.dart").write_text(
                "const int qgApiVersion = 1;\n", encoding="utf-8"
            )
            with self.assertRaises(provenance.ProvenanceError) as raised:
                provenance.read_plugin_api(root)
        self.assertIn("!= header API", str(raised.exception))


class PendingTests(unittest.TestCase):
    def test_pending_is_always_present(self) -> None:
        """A caller under `set -u` reads QFLI_PLUGIN_PENDING directly."""
        with tempfile.TemporaryDirectory() as work:
            root = Path(work)
            (root / "pubspec.lock").write_text(lock_text(), encoding="utf-8")
            (root / ".dart_tool").mkdir()
            plugin_dir = root / "plugin"
            plugin_dir.mkdir()
            (plugin_dir / "pubspec.yaml").write_text(
                "name: qfli_git\nversion: 0.2.0\n", encoding="utf-8"
            )
            (root / ".dart_tool/package_config.json").write_text(
                json.dumps(
                    {
                        "packages": [
                            {"name": "qfli_git", "rootUri": "../plugin"},
                        ]
                    }
                ),
                encoding="utf-8",
            )
            facts = provenance.collect(root, strict=False)
        self.assertEqual(facts["QFLI_PLUGIN_PENDING"], "1")
        self.assertEqual(facts["QFLI_PLUGIN_COMMIT"], COMMIT)


if __name__ == "__main__":
    unittest.main()
