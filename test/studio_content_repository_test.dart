/// Pins the QFLIStudio+ main app to the composed local curriculum.
///
/// The main product has no language filter of its own: its tutorials and
/// examples must show every sibling product's shipped content, with C and C++
/// remaining distinct subjects. The composed assets are generated by
/// `tool/generate_studio_content.dart` and audited by
/// `tool/verify_studio_content.dart`.
void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  StudioProfile? previousProfile;

  setUp(() {
    previousProfile = StudioProfile.current;
    StudioProfile.current = const StudioProfile(
      id: 'qflistudio',
      appTitle: StudioProductCatalog.qfliStudio,
      templates: [],
      productKey: StudioProductCatalog.qfliStudioKey,
      isOffline: false,
      showHomeTabs: true,
    );
  });

  tearDown(() => StudioProfile.current = previousProfile);

  test('composed catalog carries every product curriculum', () async {
    final catalog = await StudioContentRepository().load();
    final tutorialIds = catalog.tutorials.map((entry) => entry.id).toSet();
    final exampleIds = catalog.examples.map((entry) => entry.id).toSet();

    // One representative id from each product-owned catalog, including the
    // ones whose ids do not exist in the shared aggregate (Lua, Dart, Markdown,
    // Note examples) and the shared fallback subjects (Java, Python, TS, Shell).
    for (final id in const [
      'c-tutorial-001', // forge
      'cpp-tutorial-001', // forge
      'lua-chapter-start', // script (Lua product chapters)
      'js-tutorial-001', // webforge
      'rust-tutorial-101', // rustcore (past the shared 100)
      'go-tutorial-001', // goshift
      'java-tutorial-001', // jvmx (shared aggregate fallback)
      'dart-lesson-001', // dartwing
      'sql-tutorial-101', // sqlab (past the shared 100)
      'json-practical-accessible-controls-tutorial', // json
      'tutorial-markdown-basics', // note
      'shell-tutorial-001', // shared aggregate fallback
      'python-tutorial-001', // pyflow (shared aggregate fallback)
      'typescript-tutorial-001', // shared aggregate fallback
    ]) {
      expect(tutorialIds, contains(id), reason: 'missing tutorial $id');
    }
    for (final id in const [
      'c-example-001',
      'cpp-example-001',
      'lua-example-lua-clo-compose',
      'js-example-001',
      'rust-example-101',
      'go-example-001',
      'java-example-001',
      'dart-example-101',
      'sql-example-101',
      'json-practical-accessible-controls',
      'heading-h1', // note examples blocks
      'math-inline-superscript', // note examples math
      'python-example-001',
      'typescript-example-001',
      'shell-example-001',
    ]) {
      expect(exampleIds, contains(id), reason: 'missing example $id');
    }

    final subjects = catalog.tutorials
        .map((entry) => entry.language.trim().toLowerCase())
        .toSet();
    expect(
      subjects,
      containsAll(<String>[
        'c',
        'cpp',
        'lua',
        'javascript',
        'typescript',
        'shell',
        'rust',
        'go',
        'java',
        'html',
        'css',
        'python',
        'dart',
        'sql',
        'json',
        'markdown',
      ]),
    );
    // C and C++ are separate subjects, never merged into one bucket.
    expect(tutorialIds.where((id) => id.startsWith('c-tutorial-')), isNotEmpty);
    expect(
      tutorialIds.where((id) => id.startsWith('cpp-tutorial-')),
      isNotEmpty,
    );

    for (final example in catalog.examples) {
      expect(example.code.trim(), isNotEmpty, reason: example.id);
    }

    final provenance = await _loadProvenance();
    final sources = (provenance['sources'] as List)
        .cast<Map<String, Object?>>();
    final productOwned = {
      for (final source in sources)
        if (source['role'] == 'product-owned') source['product'] as String,
    };
    expect(
      productOwned,
      containsAll(<String>[
        'forge',
        'script',
        'webforge',
        'rustcore',
        'goshift',
        'dartwing',
        'sqlab',
        'json',
        'note',
      ]),
    );
    expect(_provenanceSum(provenance, 'tutorials'), catalog.tutorials.length);
    expect(_provenanceSum(provenance, 'examples'), catalog.examples.length);
  });

  testWidgets('main tutorials show all subjects with distinct C and C++', (
    tester,
  ) async {
    tester.view.physicalSize = const Size(1000, 1200);
    tester.view.devicePixelRatio = 1;
    addTearDown(tester.view.resetPhysicalSize);
    addTearDown(tester.view.resetDevicePixelRatio);

    final provenance = await tester.runAsync(_loadProvenance);
    final totalLessons = _provenanceLessonSum(provenance!);
    final cppLessons = (_provenanceLessonCounts(provenance)['cpp'] ?? 0);

    await tester.pumpWidget(
      _app(
        LocalTutorialsTab(
          language: 'qflistudio',
          repository: StudioContentRepository(),
        ),
      ),
    );
    await _waitFor(
      tester,
      () => find
          .byKey(const ValueKey('content-language-cpp'))
          .evaluate()
          .isNotEmpty,
      'main tutorial catalog',
    );

    expect(find.byKey(const ValueKey('content-language-all')), findsOneWidget);
    expect(find.byKey(const ValueKey('content-language-c')), findsOneWidget);
    expect(find.byKey(const ValueKey('content-language-cpp')), findsOneWidget);
    // The list reports the whole curriculum, not a single-language slice.
    expect(find.text('$totalLessons lessons'), findsOneWidget);

    await tester.tap(find.byKey(const ValueKey('content-language-cpp')));
    await tester.pumpAndSettle();
    expect(find.text('$cppLessons lessons'), findsOneWidget);
    expect(tester.takeException(), isNull);
    await tester.pumpWidget(const SizedBox.shrink());
  });

  testWidgets('main examples load instead of reporting a missing catalog', (
    tester,
  ) async {
    tester.view.physicalSize = const Size(1000, 1200);
    tester.view.devicePixelRatio = 1;
    addTearDown(tester.view.resetPhysicalSize);
    addTearDown(tester.view.resetDevicePixelRatio);

    final provenance = await tester.runAsync(_loadProvenance);
    final totalExamples = _provenanceSum(provenance!, 'examples');
    await tester.pumpWidget(
      _app(
        ExampleCodeTab(
          language: 'qflistudio',
          repository: StudioContentRepository(),
        ),
      ),
    );
    await _waitFor(
      tester,
      () => find
          .byKey(const ValueKey('content-language-cpp'))
          .evaluate()
          .isNotEmpty,
      'main example catalog',
    );
    final l10n = StudioLocalizations.of(
      tester.element(find.byKey(const ValueKey('content-query'))),
    );
    expect(find.text(l10n.localExamplesMissing), findsNothing);
    expect(find.text(l10n.examplesCount(totalExamples)), findsOneWidget);
    expect(tester.takeException(), isNull);
    await tester.pumpWidget(const SizedBox.shrink());
  });
}

Future<Map<String, Object?>> _loadProvenance() async =>
    jsonDecode(
          await rootBundle.loadString(StudioContentRepository.provenanceAsset),
        )
        as Map<String, Object?>;

Map<String, Object?> _provenanceCounts(
  Map<String, Object?> provenance,
  String kind,
) => (provenance['counts'] as Map)[kind] as Map<String, Object?>;

Map<String, int> _provenanceSubjects(
  Map<String, Object?> provenance,
  String kind,
) => {
  for (final entry in _provenanceCounts(provenance, kind).entries)
    entry.key: entry.value as int,
};

int _provenanceSum(Map<String, Object?> provenance, String kind) =>
    _provenanceSubjects(provenance, kind).values.fold(0, (a, b) => a + b);

Map<String, int> _provenanceLessonCounts(Map<String, Object?> provenance) => {
  for (final entry in (provenance['lessonCounts'] as Map).entries)
    entry.key as String: entry.value as int,
};

int _provenanceLessonSum(Map<String, Object?> provenance) =>
    _provenanceLessonCounts(provenance).values.fold(0, (a, b) => a + b);

MaterialApp _app(Widget home) => MaterialApp(
  locale: const Locale('en'),
  supportedLocales: StudioLocalizations.supportedLocales,
  localizationsDelegates: const [
    StudioLocalizations.delegate,
    GlobalMaterialLocalizations.delegate,
    GlobalWidgetsLocalizations.delegate,
    GlobalCupertinoLocalizations.delegate,
  ],
  theme: AppTheme.light,
  home: home,
);

Future<void> _waitFor(
  WidgetTester tester,
  bool Function() condition,
  String description,
) async {
  // Real asset I/O needs real time; pumpAndSettle advances only the fake clock.
  for (var attempt = 0; attempt < 600; attempt++) {
    await tester.runAsync(
      () => Future<void>.delayed(const Duration(milliseconds: 10)),
    );
    await tester.pump(const Duration(milliseconds: 20));
    if (condition()) return;
  }
  fail('Timed out waiting for $description');
}
